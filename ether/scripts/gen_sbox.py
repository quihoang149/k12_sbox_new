#!/usr/bin/env python3
"""Regenerate k12/keccakf_sbox.go from k12/keccakf.go.

Every block of 5 chi lines of the unrolled Keccak-f code,
    a[P] = bc_i ^ (bc_{i+2} &^ bc_{i+1})        (i = 0..4)
is replaced by the proposed S-box (thesis eq. 2.3) in bit-sliced form.

Two equivalent factorisations are available (both are checked against the
table-driven reference by TestPermutationsMatchReference):

  --variant or   (default, 35 ops/row)
      y_i = NOT( (x_i|x_{i+1}) ^ (x_{i+2} & (x_i|x_{i+4})) ^ (x_i & x_{i+3} & x_{i+4}) )
      o_k = bc_k | bc_{k+1} is shared by rows k and k+1:
      5 OR + 5 x (2 AND + 2 XOR + 1 NOT) + 5 AND = 35 ops.

  --variant p    (previous version, 40 ops/row)
      p_k = bc_k & bc_{k+2}
      y_i = NOT( (x_i|x_{i+1}) ^ (p_i &^ x_{i+4}) ^ (x_{i+4} & (x_{i+2} ^ p_{i+3})) )

Run from the repository root:  python3 scripts/gen_sbox.py [--variant or|p]
then:                          go test ./k12 -run 'SBox|Permutations' -count 1
"""
import re
import sys

variant = "or"
if "--variant" in sys.argv:
    variant = sys.argv[sys.argv.index("--variant") + 1]
if variant not in ("or", "p"):
    sys.exit("variant must be 'or' or 'p'")

HEADER = {
    "or": """// Code generated by scripts/gen_sbox.py (variant "or"); DO NOT EDIT BY HAND.

package k12

// keccakF1600SBox is Keccak-f[1600] with the chi step replaced by the
// proposed 5-bit S-box (thesis, eq. 2.3), applied to every row of 5 lanes:
//
//	y_i = 1 ^ x_i ^ x_{i+1} ^ x_i x_{i+1} ^ x_i x_{i+2} ^ x_{i+2} x_{i+4}
//	        ^ x_i x_{i+2} x_{i+4} ^ x_i x_{i+3} x_{i+4}        (indices mod 5)
//
// computed bit-sliced on 64-bit lanes in the equivalent factored form
//
//	y_i = NOT( (x_i OR x_{i+1}) ^ (x_{i+2} AND (x_i OR x_{i+4}))
//	           ^ (x_i AND x_{i+3} AND x_{i+4}) )
//
// The five o_k = x_k OR x_{k+1} are shared by rows k and k+1, so a row costs
// 5 + 5*6 = 35 operations, versus 10 for chi.
//
// theta, rho, pi and iota are unchanged. Like keccakF1600Generic it runs
// the last nr of the 24 rounds.
""",
    "p": """// Code generated by scripts/gen_sbox.py (variant "p"); DO NOT EDIT BY HAND.

package k12

// keccakF1600SBox is Keccak-f[1600] with the chi step replaced by the
// proposed 5-bit S-box (thesis, eq. 2.3), applied to every row of 5 lanes:
//
//	y_i = 1 ^ x_i ^ x_{i+1} ^ x_i x_{i+1} ^ x_i x_{i+2} ^ x_{i+2} x_{i+4}
//	        ^ x_i x_{i+2} x_{i+4} ^ x_i x_{i+3} x_{i+4}        (indices mod 5)
//
// computed bit-sliced on 64-bit lanes in an equivalent factored form with
// the shared products P_k = x_k x_{k+2}:
//
//	y_i = NOT( (x_i OR x_{i+1}) ^ (P_i AND NOT x_{i+4})
//	           ^ (x_{i+4} AND (x_{i+2} ^ P_{i+3})) )
//
// That is 5 + 5*7 = 40 operations per row, versus 10 for chi.
//
// theta, rho, pi and iota are unchanged. Like keccakF1600Generic it runs
// the last nr of the 24 rounds.
""",
}

src = open("k12/keccakf.go").read()
body = src[src.index("// keccakF1600Generic"):]
body = body[body.index("func keccakF1600Generic"):]
body = body.replace("func keccakF1600Generic(a *[25]uint64, nr int) {",
                    "func keccakF1600SBox(a *[25]uint64, nr int) {")
pat = re.compile(r"a\[(\d+)\] = bc(\d) \^ \(bc(\d) &\^ bc(\d)\)((?: \^ rc\[i(?:\+\d)?\])?)")


def rep(m):
    dst, i = m.group(1), int(m.group(2))
    assert int(m.group(3)) == (i + 2) % 5 and int(m.group(4)) == (i + 1) % 5, m.group(0)
    b = lambda k: f"bc{(i + k) % 5}"
    if variant == "or":
        o = lambda k: f"o{(i + k) % 5}"
        expr = f"^({o(0)} ^ ({b(2)} & {o(4)}) ^ ({b(0)} & {b(3)} & {b(4)}))"
    else:
        p = lambda k: f"p{(i + k) % 5}"
        expr = f"^(({b(0)} | {b(1)}) ^ ({p(0)} &^ {b(4)}) ^ ({b(4)} & ({b(2)} ^ {p(3)})))"
    return f"a[{dst}] = {expr}{m.group(5)}"


if variant == "or":
    shared = "o0, o1, o2, o3, o4 = bc0|bc1, bc1|bc2, bc2|bc3, bc3|bc4, bc4|bc0"
    extra = "o0, o1, o2, o3, o4"
else:
    shared = "p0, p1, p2, p3, p4 = bc0&bc2, bc1&bc3, bc2&bc4, bc3&bc0, bc4&bc1"
    extra = "p0, p1, p2, p3, p4"

# Insert the shared terms before the first output line of every row.
outl, n = [], 0
for ln in body.split("\n"):
    m = pat.search(ln)
    if m:
        if n % 5 == 0:
            ind = ln[: len(ln) - len(ln.lstrip())]
            outl.append(ind + shared)
        ln = pat.sub(rep, ln)
        n += 1
    outl.append(ln)
assert n == 100, f"expected 100 chi lines (4 rounds x 25 lanes), got {n}"
body = "\n".join(outl)
decl = "var t, bc0, bc1, bc2, bc3, bc4, d0, d1, d2, d3, d4 uint64"
assert decl in body
body = body.replace(decl, decl.replace(" uint64", f", {extra} uint64"))
open("k12/keccakf_sbox.go", "w").write(HEADER[variant] + body)
print(f"k12/keccakf_sbox.go regenerated (variant {variant})")
